import { FORMAT_ID } from '@terrazzo/plugin-css';
import type { Plugin } from '@terrazzo/parser';

interface DensityOverridesOptions {
	/**
	 * Output filename for the generated TypeScript module.
	 */
	filename: string;

	/**
	 * Glob-style id filter matching the tokens that should be considered. The
	 * plugin only emits overrides for tokens whose id matches this filter AND
	 * that have at least one mode-specific value.
	 */
	tokenFilter: string;

	/**
	 * Modes to emit overrides for. The special mode `.` is treated as the
	 * default mode. Each entry maps the terrazzo-side mode name to the
	 * runtime-facing key.
	 */
	modes: Array< { terrazzoMode: string; runtimeKey: string } >;
}

/**
 * Generates a TypeScript module that maps each density mode to the set of
 * CSS custom-property overrides it should apply.
 *
 * The output is consumed by the `ThemeProvider` at runtime to set those
 * overrides inline on the wrapper element, which unifies the propagation
 * model with `color` and `cursor` (issue #77462, item A8) and removes the
 * per-instance `<style>` element (item I2).
 *
 * @param options             Options for the plugin.
 * @param options.filename    Output filename for the generated module.
 * @param options.tokenFilter Glob-style id filter passed to `getTransforms`.
 * @param options.modes       Modes to include in the generated module.
 */
export default function pluginDensityOverrides( {
	filename,
	tokenFilter,
	modes,
}: DensityOverridesOptions ): Plugin {
	return {
		name: '@wordpress/terrazzo-plugin-density-overrides',
		async build( { getTransforms, outputFile } ) {
			// First pass: discover which token ids actually have mode-specific
			// values. Tokens that only exist in the default mode don't need to
			// participate in the runtime overrides because their value comes
			// from the static `:root` block in the prebuilt CSS.
			const tokensWithModeValues = new Set< string >();
			for ( const token of getTransforms( {
				format: FORMAT_ID,
				id: tokenFilter,
			} ) ) {
				if ( ! token.localID || token.mode === '.' ) {
					continue;
				}
				tokensWithModeValues.add( token.localID );
			}

			// Second pass: collect each requested mode's value for the tokens
			// identified above.
			const overrides: Record< string, Record< string, string > > = {};
			const allowedModes = new Set(
				modes.map( ( m ) => m.terrazzoMode )
			);

			for ( const token of getTransforms( {
				format: FORMAT_ID,
				id: tokenFilter,
			} ) ) {
				if (
					! token.localID ||
					! tokensWithModeValues.has( token.localID ) ||
					! allowedModes.has( token.mode ) ||
					typeof token.value !== 'string'
				) {
					continue;
				}
				const modeConfig = modes.find(
					( m ) => m.terrazzoMode === token.mode
				);
				if ( ! modeConfig ) {
					continue;
				}
				overrides[ modeConfig.runtimeKey ] ??= {};
				overrides[ modeConfig.runtimeKey ][ token.localID ] =
					token.value;
			}

			// Sort keys for stable output.
			const sortedOverrides: Record<
				string,
				Record< string, string >
			> = {};
			for ( const { runtimeKey } of modes ) {
				const modeOverrides = overrides[ runtimeKey ] ?? {};
				sortedOverrides[ runtimeKey ] = Object.fromEntries(
					Object.entries( modeOverrides ).sort( ( [ a ], [ b ] ) =>
						a.localeCompare( b )
					)
				);
			}

			outputFile(
				filename,
				[
					'/*',
					' * This file is generated by the @wordpress/terrazzo-plugin-density-overrides plugin.',
					' * Do not edit this file directly.',
					' */',
					'',
					`const densityOverrides = ${ JSON.stringify(
						sortedOverrides,
						null,
						'\t'
					) } as const;`,
					'',
					'export type DensityOverrideKey = keyof typeof densityOverrides;',
					'',
					'export default densityOverrides;',
					'',
				].join( '\n' )
			);
		},
	};
}
